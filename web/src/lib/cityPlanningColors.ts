/** 未知の区分。**色を持たせないのではなく、目立たない色にします。** */
export const ZONE_FALLBACK = "#9aa5b1";

/** MapLibre の match 式。zone_key -> 色。 */
export function zoneColorExpression(): unknown[] {
  const pairs: unknown[] = [];
  for (const [zone, color] of Object.entries(ZONE_COLORS)) {
    pairs.push(zone, color);
  }
  return ["match", ["coalesce", ["get", "zone_key"], ""], ...pairs, ZONE_FALLBACK];
}
