-- ステップごとの試行回数。
--
-- モデルの言い間違い（存在しない出典を書く、参照 id を取り違える、上限に当たって
-- JSON が途中で切れる）は一定の確率で起きます。1回で止めると、そのたびに人が
-- ボタンを押しに行くことになります。数回は黙って直させて、それでも駄目なら
-- 止める、が正しい。
--
-- ただし**何度やっても直らないもの**（残高不足・キー不正・安全性の拒否）を
-- 繰り返すと、費用だけが増えます。だから回数と一緒に「やり直す価値があるか」の
-- 判定も持ちます（kaigyou_intel.failures）。
ALTER TABLE analysis_steps ADD COLUMN IF NOT EXISTS attempts integer NOT NULL DEFAULT 0;
